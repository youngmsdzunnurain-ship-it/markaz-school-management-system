#!/usr/bin/env python3
"""Builds public/js/i18n-ar.js from the translation files in tools/i18n/dictionary/*.tsv.

Each line is:  English text <TAB> Arabic text
Use {} in the English for a changing part (a number or a name) and {0}, {1} ... in the Arabic
to put those parts back. Matching ignores letter case, curly quotes and a trailing full stop.
Run from the repo root:   python3 tools/i18n/build-dictionary.py
"""
import glob, json, re, os

def soft(s):
    s = s.replace('’', "'").replace('‘', "'").replace('“', '"').replace('”', '"').replace('…', '...')
    return ' '.join(s.split())

def norm(s):
    return re.sub(r'(\.\.\.|\.)+$', '', soft(s).lower()).strip()

exact, patterns = {}, []
here = os.path.dirname(os.path.abspath(__file__))
for f in sorted(glob.glob(os.path.join(here, 'dictionary', '*.tsv'))):
    for line in open(f, encoding='utf-8'):
        line = line.rstrip('\n')
        if not line or '\t' not in line:
            continue
        k, v = line.split('\t', 1)
        k, v = k.strip(), v.strip()
        if '{}' in k or '{$' in k:
            k = re.sub(r'\{\$[A-Za-z0-9_]+\}', '{}', k)
            parts = [re.escape(p) for p in soft(k).split('{}')]
            src = '^' + '(.+?)'.join(parts) + '$'
            patterns.append([src, v])
        else:
            exact[norm(k)] = v

out = ('/* MARKAZ Arabic dictionary (Saudi Modern Standard Arabic). GENERATED by tools/i18n/build-dictionary.py '
       'from tools/i18n/dictionary/*.tsv. Loaded only when Arabic is selected. */\n'
       'window.MARKAZ_I18N_AR = ' + json.dumps({'exact': exact, 'patterns': patterns}, ensure_ascii=False,
                                               separators=(',', ':')) + ';\n')
target = os.path.join(here, '..', '..', 'public', 'js', 'i18n-ar.js')
open(target, 'w', encoding='utf-8').write(out)
print('exact', len(exact), 'patterns', len(patterns), 'size KB', round(len(out.encode()) / 1024, 1))
